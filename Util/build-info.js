#!/usr/bin/env node
// Writes Customize/build_info.lua (git-ignored): which commit the bot scripts in this folder are.
// Customize/version.lua reads it, so the game prints the real build ([OHA-BUILD], [OHA-MATCH] version=)
// instead of a hand-bumped number. Run by the git hooks (post-checkout, post-commit, post-merge,
// post-rewrite; see .pre-commit-config.yaml), or by hand before a test game:
//
//   node Util/build-info.js
//
// version = "<HEAD commit date YYYY.MM.DD>-<short sha>"; dirty = tracked files other than
// Customize/general.lua (the local test lineup) differ from HEAD. Never fails a git command: on any
// error it prints a warning and exits 0 without touching the file.
"use strict";
const fs = require("fs");
const path = require("path");
const cp = require("child_process");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "Customize", "build_info.lua");
const IGNORED_FOR_DIRTY = new Set(["Customize/general.lua"]);

// A hook can run with GIT_INDEX_FILE pointing at a temporary index; read the real one.
const env = { ...process.env };
delete env.GIT_INDEX_FILE;

function git(args) {
	return cp.execFileSync("git", ["--no-optional-locks", ...args], { cwd: ROOT, encoding: "utf8", env });
}

function luaString(s) {
	return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n") + '"';
}

function main() {
	const commit = git(["rev-parse", "--short=7", "HEAD"]).trim();
	const branch = git(["rev-parse", "--abbrev-ref", "HEAD"]).trim();
	const date = git(["log", "-1", "--format=%cd", "--date=format:%Y.%m.%d", "HEAD"]).trim();
	const status = git(["status", "--porcelain", "--untracked-files=no"]);
	const changed = status
		.split(/\r?\n/)
		.filter(Boolean)
		.map((l) => l.slice(3).replace(/^.* -> /, "").replace(/^"|"$/g, ""));
	const dirty = changed.some((f) => !IGNORED_FOR_DIRTY.has(f));
	const lines = [
		"-- Generated by Util/build-info.js (git hooks). Git-ignored; do not edit or commit.",
		"return {",
		`\tcommit = ${luaString(commit)},`,
		`\tbranch = ${luaString(branch)},`,
		`\tdirty = ${dirty},`,
		`\tbuilt = ${luaString(new Date().toISOString().replace(/\.\d+Z$/, "Z"))},`,
		`\tversion = ${luaString(date + "-" + commit)},`,
		"}",
		"",
	];
	fs.writeFileSync(OUT, lines.join("\n"), "utf8");
	console.log(`build-info: ${date}-${commit}${dirty ? "+dirty" : ""} (${branch}) -> Customize/build_info.lua`);
}

try {
	main();
} catch (err) {
	console.warn(`build-info: skipped (${String(err.message || err).split(/\r?\n/)[0]})`);
}
process.exit(0);
