// Rebuild FuncLib/data/hero_pos_weights.lua from Dotabuff's 7-day All Pick meta table.
//
// Usage: node Util/role-weights/gen.js   (rewrites FuncLib/data/hero_pos_weights.lua in place,
//        writes rows.json beside this script for supcheck.js, prints a summary)
//
// Data: dotabuff_7d.txt, one line per hero: "Name|T49.5/12.3 ..." = tier, win rate %, pick rate %
// for pos 1..5 = core-safe, core-mid, core-off, support-off, support-safe. Source pages (one per
// position; read them in a browser, the site answers plain fetches with 403):
//   https://www.dotabuff.com/heroes?show=heroes&view=meta&mode=all-pick&date=7d&position=<pos>&rankTier=
// heroes.tsv maps Valve datafeed display names to npc names.
const fs = require("fs");
const path = require("path");
const D = __dirname, REPO = path.resolve(__dirname, "../..");
const TIER = { S: 90, A: 78, B: 66, C: 54, D: 42 };
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

// Dotabuff name -> npc name (datafeed display names; a few differ)
const disp = {};
for (const l of fs.readFileSync(D + "/heroes.tsv", "utf8").split(/\r?\n/)) {
  const p = l.split("\t"); if (p.length >= 3) disp[p[2].toLowerCase()] = p[1];
}
const alias = { "centaur warrunner": "npc_dota_hero_centaur", "treant protector": "npc_dota_hero_treant", "underlord": "npc_dota_hero_abyssal_underlord", "nature's prophet": "npc_dota_hero_furion", "outworld destroyer": "npc_dota_hero_obsidian_destroyer", "windranger": "npc_dota_hero_windrunner", "clockwerk": "npc_dota_hero_rattletrap", "io": "npc_dota_hero_wisp", "zeus": "npc_dota_hero_zuus" };
const stats = {};
for (const l of fs.readFileSync(D + "/dotabuff_7d.txt", "utf8").trim().split(/\r?\n/)) {
  const [name, rest] = l.split("|");
  const npc = disp[name.toLowerCase()] || alias[name.toLowerCase()];
  if (!npc) throw new Error("no npc for " + name);
  stats[npc] = { name, roles: rest.trim().split(/\s+/).map(s => { const m = s.match(/^([SABCD])([\d.]+)\/([\d.]+)$/); return { tier: m[1], wr: +m[2], pr: +m[3] }; }) };
}
// Key -> npc from ts_libs/dota/heroes.lua
const key2npc = {};
for (const m of fs.readFileSync(REPO + "/ts_libs/dota/heroes.lua", "utf8").matchAll(/a\.HeroName\.(\w+)\s*=\s*"([^"]+)"/g)) key2npc[m[1]] = m[2];

function weights(s) {
  const prs = s.roles.map(r => r.pr), max = Math.max(...prs), sum = prs.reduce((a, b) => a + b, 0);
  return s.roles.map(r => {
    const quality = clamp(TIER[r.tier] + clamp((r.wr - 50) * 1.5, -8, 8), 0, 100);
    const rel = max > 0 ? r.pr / max : 0;       // how this role compares with the hero's main role
    const share = sum > 0 ? r.pr / sum : 0;     // share of the hero's games played in this role
    let w = quality * Math.sqrt(rel);
    if (share < 0.05) w = Math.min(w, 5);       // almost never played here
    else if (share < 0.10) w = Math.min(w, 25); // rare off-role
    return Math.round(w);
  });
}

const target = REPO + "/FuncLib/data/hero_pos_weights.lua";
const src = fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n");
const rows = [];
let out = src.replace(/\t\[c\.(\w+)\] = \{ ([\d, ]+) \},/g, (all, key, nums) => {
  const npc = key2npc[key]; if (!npc || !stats[npc]) throw new Error("no stats for key " + key + " " + npc);
  const w = weights(stats[npc]);
  rows.push({ key, name: stats[npc].name, old: nums.split(/,\s*/).map(Number), neu: w, roles: stats[npc].roles });
  return `\t[c.${key}] = { ${w.join(", ")} },`;
});
if (rows.length !== Object.keys(stats).length) throw new Error(`table has ${rows.length} heroes, data has ${Object.keys(stats).length}`);
out = out.replace(/^(--[^\n]*\n)+/, `-- Lookup table: hero pos weights, { pos1 safe, pos2 mid, pos3 off, pos4 soft support, pos5 hard support }, 0-100.
-- Generated by Util/role-weights/gen.js from Dotabuff's All Pick meta table (last 7 days, all ranks), one page per position.
-- weight = quality * sqrt(role pick rate / the hero's highest role pick rate), where quality = tier
-- (S 90, A 78, B 66, C 54, D 42) + 1.5 per win-rate point above or below 50%, capped at +-8.
-- A role holding under 5% of the hero's role picks is capped at 5, under 10% at 25. hero_selection
-- always keeps a weight above 50 as a candidate and keeps lower ones with a chance (RandomInt(5, 50)).
`);
fs.writeFileSync(target, out);
fs.writeFileSync(D + "/rows.json", JSON.stringify(rows));
for (let p = 0; p < 5; p++) {
  const top = rows.filter(r => r.neu[p] > 50).sort((a, b) => b.neu[p] - a.neu[p]);
  console.log(`pos${p + 1}: ${top.length} always-candidates; top: ${top.slice(0, 12).map(r => r.name + " " + r.neu[p]).join(", ")}`);
}
const diffs = rows.map(r => ({ r, d: r.neu.reduce((a, v, i) => a + Math.abs(v - r.old[i]), 0) })).sort((a, b) => b.d - a.d).filter(x => x.d > 0);
console.log(diffs.length ? "\nbiggest changes:" : "\nno changes");
for (const { r } of diffs.slice(0, 25)) console.log(r.name.padEnd(20), "old", r.old.join("/").padEnd(18), "new", r.neu.join("/"));
